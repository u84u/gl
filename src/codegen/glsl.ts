const SCALAR_MAP: Record<string, string> = {
  i8: "int",
  u8: "uint",
  i16: "int",
  u16: "uint",
  i32: "int",
  u32: "uint",
  i64: "int64_t",
  u64: "uint64_t",
  f16: "float",
  f32: "float",
  f64: "double",
  bf16: "float",
  bool: "bool",
};

// Vector type prefix map shared by glslType and inferGlslElementType.
const VEC_TYPE_MAP: Record<string, string> = {
  f32: "vec",
  f16: "vec",
  f64: "dvec",
  bf16: "vec",
  i32: "ivec",
  i8: "ivec",
  i16: "ivec",
  i64: "ivec",
  u32: "uvec",
  u8: "uvec",
  u16: "uvec",
  u64: "uvec",
  bool: "bvec",
};

// Matrix type prefix map shared by glslType and inferGlslElementType.
const MAT_PREFIX_MAP: Record<string, string> = {
  f32: "",
  f64: "d",
  i32: "i",
  u32: "u",
  f16: "",
  bf16: "",
  i8: "i",
  u8: "u",
  i16: "i",
  u16: "i",
  i64: "i",
  u64: "u",
  bool: "b",
};

/**
 * Converts a gl type to its GLSL equivalent string.
 *
 * @param t - The gl type to convert.
 * @returns The GLSL type string.
 */
function glslType(t: Type): string {
  if (isScalar(t)) {
    const mapped = SCALAR_MAP[t.name];
    if (!mapped) throw new Error(`Unknown scalar type: ${t.name}`);
    return mapped;
  }
  if (isVector(t)) {
    const prefix = VEC_TYPE_MAP[t.element] || "vec";
    return `${prefix}${t.size}`;
  }
  if (isStructType(t)) return t.name;
  if (isSampler(t)) return t.name;
  if (t.kind === "quaternion") return "vec4";
  if (isMatrix(t)) {
    const prefix = MAT_PREFIX_MAP[t.element] || "";
    if (t.rows === t.columns) {
      return `${prefix}mat${t.rows}`;
    }
    return `${prefix}mat${t.columns}x${t.rows}`;
  }
  if (t.kind === "opaque") return t.name;
  if (t.kind === "anonymousStruct") {
    // Anonymous structs must be lifted to named structs for GLSL
    return `AnonStruct_${t.fields.length}`;
  }
  throw new Error(`Cannot emit GLSL type for ${t.kind}`);
}

/**
 * Generates GLSL source code from a parsed Program AST.
 *
 * @param program - The parsed Program AST.
 * @returns The generated GLSL source code string.
 * @throws Error if the program has no main function or main has invalid signature.
 */
export function generateGLSL(program: Program, target?: "glsl-450" | "glsl-es-300"): string {
  const lines: string[] = [];
  lines.push("// Generated by @u84u/gl");
  lines.push(target === "glsl-es-300" ? "#version 300 es" : "#version 450 core");
  lines.push("");

  const mainIndex = program.statements.findIndex(
    (s): s is Extract<Statement, { kind: "FnDecl" }> => s.kind === "FnDecl" && s.name === "main"
  );

  let anythingEmitted = false;
  for (let i = 0; i < program.statements.length; i++) {
    const stmt = program.statements[i];
    if (!stmt) continue;
    if (i === mainIndex) continue;
    emitStatement(lines, stmt, 0);
    anythingEmitted = true;
  }

  let stage: ShaderStage = "fragment";

  if (mainIndex !== -1) {
    const mainFnStmt = program.statements[mainIndex];
    if (!mainFnStmt) {
      throw new Error("main statement is undefined");
    }
    if (!isFnDecl(mainFnStmt)) {
      throw new Error("main is not a function declaration");
    }
    const mainFn = mainFnStmt;
    stage = mainFn.stage ?? "fragment";
    const returnType = mainFn.returnType;
    if (mainFn.params.length > 0) {
      throw new Error("main must take no parameters");
    }
    if (anythingEmitted) {
      lines.push("");
    }

    if (stage === "fragment") {
      if (isVector(returnType) && returnType.size === 4) {
        lines.push("out vec4 fragColor;");
        lines.push("");
        lines.push("void main() {");
        for (const s of mainFn.body.statements) {
          emitStatement(lines, s, 1, { structName: "", fields: [] });
        }
        lines.push("}");
      } else if (isStructType(returnType)) {
        const structDecl = program.statements.find(
          (s): s is StructDecl => s.kind === "StructDecl" && s.name === returnType.name
        );
        if (!structDecl) {
          throw new Error(`Unknown struct '${returnType.name}'`);
        }
        for (let i = 0; i < structDecl.fields.length; i++) {
          const field = structDecl.fields[i];
          if (!field) continue;
          const glslTypeName = glslType(field.type);
          lines.push(`layout(location = ${i}) out ${glslTypeName} ${field.name};`);
        }
        lines.push("");
        lines.push("void main() {");
        const outputInfo = { structName: returnType.name, fields: structDecl.fields };
        for (const s of mainFn.body.statements) {
          emitStatement(lines, s, 1, outputInfo);
        }
        lines.push("}");
      } else {
        throw new Error("fragment main must return vec4 or a struct");
      }
    } else if (stage === "vertex") {
      if (isVector(returnType) && returnType.size === 4) {
        lines.push("out vec4 gl_Position;");
        lines.push("");
        lines.push("void main() {");
        for (const s of mainFn.body.statements) {
          emitStatement(lines, s, 1, { structName: "", fields: [] });
        }
        lines.push("}");
      } else {
        throw new Error("vertex main must return vec4 (position)");
      }
    } else if (stage === "compute") {
      lines.push("layout(local_size_x = 1, local_size_y = 1, local_size_z = 1) in;");
      lines.push("");
      lines.push("void main() {");
      for (const s of mainFn.body.statements) {
        emitStatement(lines, s, 1, { structName: "", fields: [] });
      }
      lines.push("}");
    } else {
      throw new Error(`Unknown shader stage: ${stage}`);
    }
  } else {
    throw new Error(`No main function found — ${stage} shaders require an entry point`);
  }

  return lines.join("\n") + "\n";
}

/**
 * Emits GLSL code for a statement into the output lines array.
 *
 * @param lines - The output lines array to append to.
 * @param stmt - The statement to emit.
 * @param indent - The indentation level (number of 2-space indent units).
 * @param outputInfo - Optional output struct info for main function returns.
 */
function emitStatement(
  lines: string[],
  stmt: Statement,
  indent: number,
  outputInfo: { structName: string; fields: { name: string; type: Type }[] } | null = null,
): void {
  const pad = "  ".repeat(indent);
  if (isStructDecl(stmt)) {
    lines.push(`${pad}struct ${stmt.name} {`);
    for (const field of stmt.fields) {
      let fieldType: string;
      let fieldSuffix = "";
      if (isArray(field.type)) {
        fieldType = glslType(field.type.element);
        fieldSuffix = `[${field.type.size}]`;
      } else {
        fieldType = glslType(field.type);
      }
      lines.push(`${pad}  ${fieldType} ${field.name}${fieldSuffix};`);
    }
    lines.push(`${pad}};`);
    return;
  }
  if (isBindingDecl(stmt)) {
    let declType: string;
    let declSuffix = "";
    if (isArray(stmt.type)) {
      declType = glslType(stmt.type.element);
      declSuffix = `[${stmt.type.size}]`;
    } else {
      declType = glslType(stmt.type);
    }
    const isSamplerBinding = isSampler(stmt.type);
    const bindingDecl = isSamplerBinding
      ? `layout(binding = ${stmt.binding}) uniform ${declType} ${stmt.name}${declSuffix};`
      : `uniform ${declType} ${stmt.name}${declSuffix};`;
    lines.push(`${pad}${bindingDecl}`);
    return;
  }
  if (isFnDecl(stmt)) {
    const params = stmt.params
      .map((p) => `${glslType(p.type)} ${p.name}`)
      .join(", ");
    lines.push(`${pad}${glslType(stmt.returnType)} ${stmt.name}(${params}) {`);
    for (const s of stmt.body.statements) {
      emitStatement(lines, s, indent + 1, null);
    }
    lines.push(`${pad}}`);
    return;
  }
  if (isVarDecl(stmt)) {
    let declType: string;
    let declSuffix = "";
    if (isArray(stmt.type)) {
      declType = glslType(stmt.type.element);
      declSuffix = `[${stmt.type.size}]`;
    } else {
      declType = glslType(stmt.type);
    }
    let init = "";
    if (stmt.initializer) {
      if (isStructLiteral(stmt.initializer)) {
        const args = stmt.initializer.fields.map((f) => {
          if (f.name === null) return `..${emitExpression(f.value)}`;
          return emitExpression(f.value);
        }).join(", ");
        init = ` = ${declType}(${args})`;
      } else {
        init = ` = ${emitExpression(stmt.initializer)}`;
      }
    }
    lines.push(`${pad}${declType} ${stmt.name}${declSuffix}${init};`);
    return;
  }
  if (isReturnStmt(stmt)) {
    if (!stmt.value) {
      if (outputInfo) {
        throw new Error("main must return a value");
      }
      lines.push(`${pad}return;`);
      return;
    }
    if (outputInfo) {
      if (outputInfo.fields.length > 0) {
        lines.push(`${pad}${outputInfo.structName} outVal = ${emitExpression(stmt.value)};`);
        for (const field of outputInfo.fields) {
          lines.push(`${pad}${field.name} = outVal.${field.name};`);
        }
      } else {
        if (isStructLiteral(stmt.value)) {
          const args = stmt.value.fields.map((f) => emitExpression(f.value)).join(", ");
          lines.push(`${pad}fragColor = vec4(${args});`);
        } else {
          lines.push(`${pad}fragColor = ${emitExpression(stmt.value)};`);
        }
      }
    } else {
      lines.push(`${pad}return ${emitExpression(stmt.value)};`);
    }
    return;
  }
  if (isExpressionStmt(stmt)) {
    lines.push(`${pad}${emitExpression(stmt.expression)};`);
    return;
  }
  if (isBlock(stmt)) {
    lines.push(`${pad}{`);
    for (const s of stmt.statements) {
      emitStatement(lines, s, indent + 1, outputInfo);
    }
    lines.push(`${pad}}`);
    return;
  }
  if (isIfStmt(stmt)) {
    lines.push(`${pad}if (${emitExpression(stmt.condition)}) {`);
    for (const s of stmt.thenBranch.statements) {
      emitStatement(lines, s, indent + 1, outputInfo);
    }
    lines.push(`${pad}}`);
    if (stmt.elseBranch) {
      lines.push(`${pad}else {`);
      for (const s of stmt.elseBranch.statements) {
        emitStatement(lines, s, indent + 1, outputInfo);
      }
      lines.push(`${pad}}`);
    }
    return;
  }
  if (isWhileStmt(stmt)) {
    lines.push(`${pad}while (${emitExpression(stmt.condition)}) {`);
    for (const s of stmt.body.statements) {
      emitStatement(lines, s, indent + 1, outputInfo);
    }
    lines.push(`${pad}}`);
    return;
  }
  if (isForStmt(stmt)) {
    if (stmt.range) {
      const startCode = emitExpression(stmt.range.start);
      const endCode = emitExpression(stmt.range.end);
      const condOp = stmt.range.inclusive ? "<=" : "<";
      // Loop variable is implicitly an int
      lines.push(`${pad}for (int __loop_var = ${startCode}; __loop_var ${condOp} ${endCode}; __loop_var++) {`);
      for (const s of stmt.body.statements) {
        emitStatement(lines, s, indent + 1, outputInfo);
      }
      lines.push(`${pad}}`);
      return;
    }
    let initStr = "";
    if (stmt.init) {
      if (isVarDecl(stmt.init)) {
        initStr = emitVarDeclStr(stmt.init);
      } else if (isExpressionStmt(stmt.init)) {
        initStr = emitExpression(stmt.init.expression);
      }
    }
    let condStr = stmt.condition ? emitExpression(stmt.condition) : "";
    let incrStr = stmt.increment ? emitExpression(stmt.increment) : "";
    lines.push(`${pad}for (${initStr}; ${condStr}; ${incrStr}) {`);
    for (const s of stmt.body.statements) {
      emitStatement(lines, s, indent + 1, outputInfo);
    }
    lines.push(`${pad}}`);
    return;
  }
  if (isDoWhileStmt(stmt)) {
    lines.push(`${pad}do {`);
    for (const s of stmt.body.statements) {
      emitStatement(lines, s, indent + 1, outputInfo);
    }
    lines.push(`${pad}} while (${emitExpression(stmt.condition)});`);
    return;
  }
  if (isLoopStmt(stmt)) {
    lines.push(`${pad}for (;;) {`);
    for (const s of stmt.body.statements) {
      emitStatement(lines, s, indent + 1, outputInfo);
    }
    lines.push(`${pad}}`);
    return;
  }
  if (isBreakStmt(stmt)) {
    lines.push(`${pad}break;`);
    return;
  }
  if (isContinueStmt(stmt)) {
    lines.push(`${pad}continue;`);
    return;
  }
  if (isPanicStmt(stmt)) {
    if (stmt.message) {
      lines.push(`${pad}// panic: ${emitExpression(stmt.message)}`);
    } else {
      lines.push(`${pad}// panic`);
    }
    return;
  }
  if (isUnreachableStmt(stmt)) {
    lines.push(`${pad}// unreachable`);
    return;
  }
  if (isDiscardStmt(stmt)) {
    lines.push(`${pad}discard;`);
    return;
  }
  // TypeAlias, NewtypeDecl, OpaqueDecl, EnumDecl, ImplBlock, TraitDecl — transparent
}

/**
 * Emits a GLSL variable declaration string (without trailing semicolon).
 *
 * @param stmt - The VarDecl statement to emit.
 * @returns The GLSL declaration string.
 */
function emitVarDeclStr(stmt: Extract<Statement, { kind: "VarDecl" }>): string {
  let declType: string;
  let declSuffix = "";
  if (isArray(stmt.type)) {
    declType = glslType(stmt.type.element);
    declSuffix = `[${stmt.type.size}]`;
  } else {
    declType = glslType(stmt.type);
  }
  let init = "";
  if (stmt.initializer) {
    if (isStructLiteral(stmt.initializer)) {
      const args = stmt.initializer.fields.map((f) => {
        if (f.name === null) return `..${emitExpression(f.value)}`;
        return emitExpression(f.value);
      }).join(", ");
      init = ` = ${declType}(${args})`;
    } else {
      init = ` = ${emitExpression(stmt.initializer)}`;
    }
  }
  return `${declType} ${stmt.name}${declSuffix}${init}`;
}

/**
 * Emits GLSL code for an expression.
 *
 * @param expr - The expression to emit.
 * @returns The GLSL expression string.
 */
function emitExpression(expr: Expression): string {
  if (isIdentifier(expr)) {
    return expr.name;
  }
  if (isLiteral(expr)) {
    return emitLiteral(expr);
  }
  if (isBinaryExpr(expr)) {
    return `(${emitExpression(expr.left)} ${expr.operator} ${emitExpression(expr.right)})`;
  }
  if (isUnaryExpr(expr)) {
    return `(${expr.operator}${emitExpression(expr.operand)})`;
  }
  if (isCallExpr(expr)) {
    const calleeName =
      expr.callee.kind === "Identifier" ? expr.callee.name : emitExpression(expr.callee);
    const args = expr.args.map(emitExpression).join(", ");
    const glslBuiltin = glslBuiltinName(calleeName);
    if (glslBuiltin && glslBuiltin.kind === "builtin") {
      return `${glslBuiltin.name}(${args})`;
    }
    if (glslBuiltin && glslBuiltin.kind === "rotate") {
      const xExpr = expr.args[0];
      const sExpr = expr.args[1];
      if (!xExpr || !sExpr) {
        throw new Error("rotateLeft/rotateRight require two arguments");
      }
      const xCode = emitExpression(xExpr);
      const sCode = emitExpression(sExpr);
      const dir = glslBuiltin.dir;
      return `(${xCode} ${dir === "left" ? "<<" : ">>"} ${sCode}) | (${xCode} ${dir === "left" ? ">>" : "<<"} (32 - ${sCode}))`;
    }
    return `${calleeName}(${args})`;
  }
  if (isMemberExpr(expr)) {
    return `${emitExpression(expr.object)}.${expr.property}`;
  }
  if (isSwizzleExpr(expr)) {
    const swizzle = expr.components.join("");
    return `${emitExpression(expr.object)}.${swizzle}`;
  }
  if (isIndexExpr(expr)) {
    return `${emitExpression(expr.object)}[${emitExpression(expr.index)}]`;
  }
  if (isStructLiteral(expr)) {
    const fields = expr.fields.map((f) => {
      if (f.name === null) return `..${emitExpression(f.value)}`;
      return emitExpression(f.value);
    }).join(", ");
    return `${expr.typeName}(${fields})`;
  }
  if (isArrayLiteral(expr)) {
    const elements = expr.elements.map(emitExpression).join(", ");
    const elemType = expr.elements.length > 0 ? inferGlslElementType(expr.elements[0]!) : "float";
    return `${elemType}[${expr.elements.length}](${elements})`;
  }
  if (isCompoundAssignExpr(expr)) {
    return `(${emitExpression(expr.target)} = ${emitExpression(expr.target)} ${expr.operator.slice(0, -1)} ${emitExpression(expr.value)})`;
  }
  if (isUpdateExpr(expr)) {
    const op = expr.operator === "++" ? "+ 1" : "- 1";
    if (expr.prefix) {
      return `(${emitExpression(expr.operand)} = ${emitExpression(expr.operand)} ${op}, ${emitExpression(expr.operand)})`;
    }
    return `(${emitExpression(expr.operand)} = ${emitExpression(expr.operand)} ${op})`;
  }
  if (isConditionalExpr(expr)) {
    return `(${emitExpression(expr.test)} ? ${emitExpression(expr.consequent)} : ${emitExpression(expr.alternate)})`;
  }
  if (isNullCoalescingExpr(expr)) {
    return `(${emitExpression(expr.left)} != 0 ? ${emitExpression(expr.left)} : ${emitExpression(expr.right)})`;
  }
  if (isMatchExpr(expr)) {
    const subjectCode = emitExpression(expr.subject);
    const branches: string[] = [];
    for (let i = 0; i < expr.arms.length; i++) {
      const arm = expr.arms[i]!;
      let condition = "true";
      if (isLiteralPattern(arm.pattern) && arm.pattern.value !== null) {
        condition = `(${subjectCode} == ${arm.pattern.value})`;
      }
      const bodyCode = emitMatchBodyToString(arm.body.statements);
      if (i === expr.arms.length - 1 && isBindingPattern(arm.pattern)) {
        branches.push(`else { ${bodyCode} }`);
      } else {
        branches.push(`if (${condition}) { ${bodyCode} }`);
      }
    }
    return `(${branches.join(" ")})`;
  }
  if (isBlockExpr(expr)) {
    const stmts = expr.block.statements;
    if (stmts.length === 0) return "0.0";
    const last = stmts[stmts.length - 1]!;
    if (isExpressionStmt(last)) {
      return emitExpression(last.expression);
    }
    return "0.0";
  }
  throw new Error("Cannot emit GLSL expression");
}

/**
 * Type guard: literal pattern.
 */
function isLiteralPattern(p: { kind: string }): p is { kind: "literal"; value: number | string | boolean } {
  return p.kind === "literal";
}

/**
 * Type guard: binding pattern.
 */
function isBindingPattern(p: { kind: string }): p is { kind: "binding"; binding: string } {
  return p.kind === "binding";
}

/**
 * Emits GLSL code for a list of statements as a flat string (used inside match arms).
 *
 * @param stmts - The statements to emit.
 * @returns The concatenated GLSL code string.
 */
function emitMatchBodyToString(stmts: Statement[]): string {
  const parts: string[] = [];
  for (const s of stmts) {
    if (isReturnStmt(s)) {
      if (s.value) {
        parts.push(`return ${emitExpression(s.value)};`);
      } else {
        parts.push("return;");
      }
    } else if (isExpressionStmt(s)) {
      parts.push(`${emitExpression(s.expression)};`);
    } else if (isDiscardStmt(s)) {
      parts.push("discard;");
    } else if (isPanicStmt(s)) {
      parts.push(s.message ? `panic ${emitExpression(s.message)};` : "panic;");
    } else if (isUnreachableStmt(s)) {
      parts.push("unreachable;");
    } else if (isBreakStmt(s)) {
      parts.push("break;");
    } else if (isContinueStmt(s)) {
      parts.push("continue;");
    } else if (isBlock(s)) {
      parts.push("{ ");
      for (const inner of s.statements) {
        parts.push(emitMatchBodyToString([inner]));
      }
      parts.push(" }");
    } else if (isIfStmt(s)) {
      parts.push(`if (${emitExpression(s.condition)}) { `);
      for (const inner of s.thenBranch.statements) {
        parts.push(emitMatchBodyToString([inner]));
      }
      parts.push(" }");
      if (s.elseBranch) {
        parts.push(" else { ");
        for (const inner of s.elseBranch.statements) {
          parts.push(emitMatchBodyToString([inner]));
        }
        parts.push(" }");
      }
    } else if (isVarDecl(s)) {
      let init = "";
      if (s.initializer) {
        if (isStructLiteral(s.initializer)) {
          const args = s.initializer.fields.map((f) => emitExpression(f.value)).join(", ");
          init = ` = ${glslType(s.type)}(${args})`;
        } else {
          init = ` = ${emitExpression(s.initializer)}`;
        }
      }
      parts.push(`${glslType(s.type)} ${s.name}${init};`);
    } else if (isWhileStmt(s)) {
      parts.push(`while (${emitExpression(s.condition)}) { `);
      for (const inner of s.body.statements) {
        parts.push(emitMatchBodyToString([inner]));
      }
      parts.push(" }");
    } else if (isForStmt(s)) {
      parts.push("for (;;) { ");
      for (const inner of s.body.statements) {
        parts.push(emitMatchBodyToString([inner]));
      }
      parts.push(" }");
    } else if (isDoWhileStmt(s)) {
      parts.push("do { ");
      for (const inner of s.body.statements) {
        parts.push(emitMatchBodyToString([inner]));
      }
      parts.push(`} while (${emitExpression(s.condition)});`);
    } else if (isLoopStmt(s)) {
      parts.push("for (;;) { ");
      for (const inner of s.body.statements) {
        parts.push(emitMatchBodyToString([inner]));
      }
      parts.push(" }");
    }
  }
  return parts.join(" ");
}

/**
 * Maps a gl built-in function name to its GLSL equivalent or rotate operation.
 *
 * @param name - The gl built-in function name.
 * @returns A built-in descriptor, or null if the name is not a recognized built-in.
 */
function glslBuiltinName(name: string): { kind: "builtin"; name: string } | { kind: "rotate"; dir: "left" | "right" } | null {
  const map: Record<string, string> = {
    bitCount: "bitCount",
    extract: "bitfieldExtract",
    insert: "bitfieldInsert",
    reverse: "bitfieldReverse",
  };
  const mapped = map[name];
  if (mapped) return { kind: "builtin", name: mapped };
  if (name === "rotateLeft") return { kind: "rotate", dir: "left" };
  if (name === "rotateRight") return { kind: "rotate", dir: "right" };
  return null;
}

/**
 * Emits GLSL code for a literal expression.
 *
 * @param expr - The Literal expression to emit.
 * @returns The GLSL literal string.
 */
function emitLiteral(expr: Extract<Expression, { kind: "Literal" }>): string {
  const { value } = expr;
  if (isLiteralOfKind(expr, "bool")) return value ? "true" : "false";
  if (isLiteralOfKind(expr, "int")) return `${typeof value === "number" ? value : Number(value)}`;
  if (isLiteralOfKind(expr, "float")) {
    const f = typeof value === "number" ? value : Number(value);
    if (Number.isInteger(f)) return `${f}.0`;
    return String(f);
  }
  if (isLiteralOfKind(expr, "char")) {
    return charToCode(typeof value === "string" ? value : String(value)).toString();
  }
  if (isLiteralOfKind(expr, "color")) {
    return `0x${typeof value === "string" ? value : String(value)}`;
  }
  return String(value);
}

/**
 * Converts a character literal to its numeric code point.
 *
 * @param s - The character string (single char or escape sequence).
 * @returns The numeric code point.
 */
function charToCode(s: string): number {
  if (s.length === 1) return s.charCodeAt(0);
  switch (s) {
    case "\\n": return 10;
    case "\\t": return 9;
    case "\\r": return 13;
    case "\\\\": return 92;
    case "\\'": return 39;
    case '\\"': return 34;
    case "\\0": return 0;
    default: return 0;
  }
}

/**
 * Infers the GLSL element type string from an expression (used for array literals).
 *
 * @param expr - The expression to infer the element type from.
 * @returns The GLSL element type string.
 */
function inferGlslElementType(expr: Expression): string {
  if (isLiteral(expr)) {
    if (isLiteralOfKind(expr, "int")) return "int";
    if (isLiteralOfKind(expr, "float")) return "float";
    if (isLiteralOfKind(expr, "bool")) return "bool";
  }
  if (isCallExpr(expr)) {
    const callee = expr.callee;
    if (isIdentifier(callee)) {
      const name = callee.name;
      if (name.startsWith("mat")) {
        let base = name;
        let prefix = "";
        for (const [k, v] of Object.entries(MAT_PREFIX_MAP)) {
          if (base.startsWith(k)) {
            prefix = v;
            base = base.slice(k.length);
            break;
          }
        }
        return `${prefix}mat${base}`;
      }
      if (name.startsWith("vec")) {
        return name;
      }
      if (name === "quat") return "vec4";
      return "float";
    }
  }
  return "float";
}

/**
 * Recursively collects every Type node nested inside a type expression.
 *
 * @param t - The type to walk.
 * @param out - The array to append collected types to.
 */
function collectTypes(t: Type, out: Type[]): void {
  out.push(t);
  if (isVector(t)) return;
  if (isMatrix(t)) return;
  if (isArray(t)) {
    collectTypes(t.element, out);
    return;
  }
  if (t.kind === "tuple") {
    for (const element of t.elements) collectTypes(element, out);
    return;
  }
  if (t.kind === "option") {
    collectTypes(t.element, out);
    return;
  }
  if (t.kind === "result") {
    collectTypes(t.ok, out);
    collectTypes(t.err, out);
    return;
  }
  if (t.kind === "anonymousStruct") {
    for (const field of t.fields) collectTypes(field.type, out);
    return;
  }
  if (t.kind === "union") {
    for (const member of t.members) collectTypes(member, out);
    return;
  }
}

/**
 * Validates that every scalar type in the program is supported by the given
 * GLSL target capabilities. Returns diagnostics for unsupported types.
 *
 * @param program - The program to validate.
 * @param capabilities - The target backend capabilities.
 * @returns Diagnostics for unsupported scalar types.
 */
export function validateGLSLModule(
  program: Program,
  file: string,
  capabilities: BackendCapabilities,
): Diagnostic[] {
  const diagnostics: Diagnostic[] = [];
  const seen = new Set<Type>();

  function checkType(t: Type, span: Span): void {
    const nested: Type[] = [];
    collectTypes(t, nested);
    for (const nt of nested) {
      if (seen.has(nt)) continue;
      seen.add(nt);
      if (isScalar(nt)) {
        const name = nt.name as ScalarTypeName;
        if (!scalarIsSupported(capabilities, name)) {
          diagnostics.push(
            diagnostic(
              file,
              span,
              `GLSL does not support scalar type '${name}'`,
              {
                code: "GLSL_UNSUPPORTED_SCALAR",
                severity: "error",
                help: `Convert to a supported type (${Array.from(capabilities.scalarTypes).join(", ")}) or use an explicit cast.`,
              },
            ),
          );
        }
      }
    }
  }

  function walkStatements(stmts: Statement[]): void {
    for (const stmt of stmts) {
      if (isVarDecl(stmt)) checkType(stmt.type, stmt.span);
      if (isBindingDecl(stmt)) checkType(stmt.type, stmt.span);
      if (isFnDecl(stmt)) {
        for (const param of stmt.params) checkType(param.type, stmt.span);
        checkType(stmt.returnType, stmt.span);
        walkStatements(stmt.body.statements);
      }
      if (isStructDecl(stmt)) {
        for (const field of stmt.fields) checkType(field.type, stmt.span);
      }
      if (isEnumDecl(stmt)) {
        for (const variant of stmt.variants) {
          if (variant.type) checkType(variant.type, stmt.span);
        }
      }
      if (isTypeAlias(stmt)) {
        checkType(stmt.type, stmt.span);
      }
      if (isNewtypeDecl(stmt)) {
        checkType(stmt.innerType, stmt.span);
      }
      if (isTraitDecl(stmt)) {
        for (const method of stmt.methods) {
          for (const param of method.params) checkType(param.type, stmt.span);
          checkType(method.returnType, stmt.span);
        }
      }
      if (isImplBlock(stmt)) {
        checkType(stmt.type, stmt.span);
        for (const method of stmt.methods) {
          for (const param of method.params) checkType(param.type, stmt.span);
          checkType(method.returnType, stmt.span);
        }
      }
      if (isBlock(stmt)) walkStatements(stmt.statements);
      if (isIfStmt(stmt)) {
        walkStatements(stmt.thenBranch.statements);
        if (stmt.elseBranch) walkStatements(stmt.elseBranch.statements);
      }
      if (isWhileStmt(stmt)) walkStatements(stmt.body.statements);
      if (isForStmt(stmt)) walkStatements(stmt.body.statements);
      if (isDoWhileStmt(stmt)) walkStatements(stmt.body.statements);
      if (isLoopStmt(stmt)) walkStatements(stmt.body.statements);
    }
  }

  walkStatements(program.statements);
  return diagnostics;
}

/**
 * GLSL code-generation backend. Supports "glsl-450" and "glsl" (alias).
 */
export class GlslBackend implements ShaderCodegenBackend {
  readonly version = "4.50";
  readonly capabilities: BackendCapabilities = GLSL_450_CAPABILITIES;

  constructor(readonly id: ShaderTarget) {}

  validate(ast: unknown, file: string): Diagnostic[] {
    if (!isProgram(ast)) {
      return [{
        file,
        span: { line: 1, column: 1 },
        message: "Invalid program passed to GLSL backend",
        code: "INVALID_PROGRAM",
        severity: "error",
      }];
    }
    return validateGLSLModule(ast, file, this.capabilities);
  }

  generate(
    ast: unknown,
    _file: string,
    _options: CodegenOptions = {},
  ): BackendOutput {
    if (!isProgram(ast)) {
      return {
        target: this.id,
        shaders: [],
        diagnostics: [{
          file: _file,
          span: { line: 1, column: 1 },
          message: "Invalid program passed to GLSL backend",
          code: "INVALID_PROGRAM",
          severity: "error",
        }],
      };
    }
    const program = ast;
    const diagnostics: Diagnostic[] = [];
    let code: string | null = null;

    try {
      const target = this.id === "glsl" ? "glsl-450" : this.id;
      code = generateGLSL(program, target as "glsl-450" | "glsl-es-300");
    } catch (err) {
      diagnostics.push({
        file: _file,
        span: { line: 1, column: 1 },
        message: err instanceof Error ? err.message : String(err),
        severity: "error",
      });
    }

    const shaders: ShaderArtifact[] = [];
    if (code) {
      const mainStmt = program.statements.find(
        (s): s is Extract<Statement, { kind: "FnDecl" }> =>
          s.kind === "FnDecl" && s.name === "main",
      );
      const stage = mainStmt?.stage ?? "fragment";
      shaders.push({
        stage,
        entryPoint: "main",
        code,
        reflection: {
          entryPoints: [],
          resources: [],
          uniforms: [],
        },
      } as ShaderArtifact);
    }

    return {
      target: this.id,
      shaders,
      diagnostics,
    };
  }
}

export const glsl450Backend = new GlslBackend("glsl-450");
export const glslBackend = new GlslBackend("glsl");
defaultRegistry.register(glsl450Backend);
defaultRegistry.register(glslBackend);


